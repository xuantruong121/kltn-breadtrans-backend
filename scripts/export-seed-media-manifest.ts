/**
 * Read-only: writes prisma/seed-data/practice-media.json from a database whose
 * media layout is authoritative (normally kltn_db after Checkpoint 52), so the
 * canonical seed relinks practice media to the objects that really exist in
 * R2 instead of guessing public keys:
 *   - listeningAssets: every QuizAudioAsset of a LISTENING_PRACTICE quiz
 *     (questionId, version, key, isActive, mimeType);
 *   - speakingAudio: SpeakingExercise id → reference audio key of standalone
 *     practice (a public URL is reduced to its object key, so the manifest
 *     carries no bucket host).
 * Keys and public URLs of authored content only; no learner data, no secrets.
 *
 * Usage: npx ts-node --transpile-only scripts/export-seed-media-manifest.ts --target env:DATABASE_URL
 */
import { mkdirSync, writeFileSync } from 'node:fs';

import { PrismaClient } from '@prisma/client';

async function main() {
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  require('dotenv').config({ quiet: true });
  const i = process.argv.indexOf('--target');
  const target = i > 0 ? process.argv[i + 1] : undefined;
  const url = target === 'env:DATABASE_URL' ? process.env.DATABASE_URL : target;
  if (!url) throw new Error('--target env:DATABASE_URL | <url> is required');
  const prisma = new PrismaClient({ datasources: { db: { url } } });
  try {
    await prisma.$executeRawUnsafe('SET default_transaction_read_only = on');
    const listeningAssets = await prisma.quizAudioAsset.findMany({
      where: { question: { quiz: { type: 'LISTENING_PRACTICE' } } },
      select: {
        questionId: true,
        version: true,
        key: true,
        isActive: true,
        mimeType: true,
      },
      orderBy: [{ questionId: 'asc' }, { version: 'asc' }],
    });
    const speaking = await prisma.speakingExercise.findMany({
      where: {
        audioUrl: { not: null },
        OR: [
          { practiceSetId: null },
          { practiceSet: { scope: 'SKILL_PRACTICE' } },
        ],
      },
      select: { id: true, audioUrl: true },
      orderBy: { id: 'asc' },
    });
    mkdirSync('prisma/seed-data', { recursive: true });
    writeFileSync(
      'prisma/seed-data/practice-media.json',
      `${JSON.stringify(
        {
          note: 'Generated by scripts/export-seed-media-manifest.ts; authored practice media as stored in R2.',
          listeningAssets,
          speakingAudio: Object.fromEntries(
            speaking.map((s) => [
              s.id,
              s.audioUrl!.startsWith('http')
                ? new URL(s.audioUrl!).pathname.slice(1)
                : s.audioUrl,
            ]),
          ),
        },
        null,
        2,
      )}\n`,
    );
    console.log(
      `listening assets: ${listeningAssets.length}; speaking audio: ${speaking.length}`,
    );
  } finally {
    await prisma.$disconnect();
  }
}

main().catch((e) => {
  console.error('STOPPED:', e instanceof Error ? e.message : e);
  process.exit(1);
});
