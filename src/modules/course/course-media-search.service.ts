import {
  ConflictException,
  ForbiddenException,
  Injectable,
  NotFoundException,
  Optional,
} from '@nestjs/common';
import { CourseLessonStatus, CourseStatus, Role } from '@prisma/client';
import { randomUUID } from 'crypto';
import { InjectRedis } from '@nestjs-modules/ioredis';
import Redis from 'ioredis';
import { PrismaService } from '../../prisma/prisma.service';
import { UploadService } from '../upload/upload.service';
import { AiImageSemanticValidator } from '../ai/ai-image-semantic-validator.service';
import { ImageSearchProviderChain } from '../toeic/image-search.provider-chain';
import {
  ImageSearchCandidate,
  validateImageBuffer,
} from '../toeic/pixabay-image-search.provider';
import {
  AcceptCourseMediaDto,
  AcceptGeneratedMediaDto,
  SearchCourseMediaDto,
} from './course-media.dto';

type Admin = { id: number; role: Role };

/** Distinguishes WHY no candidate was returned, so the Admin never sees "no
 * results" when the real reason was a provider or Gemini outage. */
export type MediaSearchReason =
  | 'SUCCESS'
  | 'SEARCH_NO_RESULT'
  | 'SEARCH_PROVIDER_UNAVAILABLE'
  | 'VISION_REJECTED_ALL'
  | 'VISION_UNAVAILABLE';

/** Distinguishes why an AI-generation attempt did not produce an acceptable
 * candidate. Separate from MediaSearchReason: generation is a different
 * authoring action with its own provenance (synthetic, not existing media). */
export type MediaGenerationReason =
  | 'SUCCESS'
  | 'AI_IMAGE_GENERATION_NOT_CONFIGURED'
  | 'AI_IMAGE_GENERATION_FAILED'
  | 'AI_IMAGE_GENERATION_STORAGE_FAILED'
  | 'TEMP_MEDIA_STORAGE_UNAVAILABLE'
  | 'VISION_REJECTED_ALL'
  | 'VISION_UNAVAILABLE';

const CLOUDFLARE_MODEL = '@cf/black-forest-labs/flux-1-schnell';
/** 10 minutes — matches the previous in-memory policy. */
const GENERATION_TOKEN_TTL_SECONDS = 600;

type GeneratedMediaType = 'COURSE_COVER' | 'LESSON_IMAGE';

/** Lightweight metadata only — generated bytes themselves live in a
 * temporary R2 object, never in Redis. Shared across backend instances, so
 * Accept on instance B works for a candidate generated on instance A. */
type GeneratedMediaMetadata = {
  token: string;
  temporaryObjectKey: string;
  mediaType: GeneratedMediaType;
  courseId: number;
  lessonId?: number;
  mimeType: string;
  width: number;
  height: number;
  generatedAt: number;
  provider: 'CLOUDFLARE_WORKERS_AI';
  model: string;
  semanticStatus: 'PASS' | 'LOW_CONFIDENCE' | 'UNAVAILABLE';
};

const MAX_MEDIA_CANDIDATES_TO_VISION = 3;
const LEVEL_LABEL: Record<string, string> = {
  BEGINNER: 'beginner',
  INTERMEDIATE: 'intermediate',
  ADVANCED: 'advanced',
};
const STOPWORDS = new Set([
  'a',
  'an',
  'the',
  'and',
  'or',
  'for',
  'with',
  'in',
  'on',
  'at',
  'to',
  'of',
  'your',
  'you',
  'is',
  'are',
]);

/** Image search providers match short keyword phrases far better than full
 * sentences — reduce a title down to its meaningful words. */
function keywordize(text: string, maxWords = 6): string {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, ' ')
    .split(/\s+/)
    .filter((word) => word && !STOPWORDS.has(word))
    .slice(0, maxWords)
    .join(' ');
}

/** Free-first media search: Pixabay → Openverse → Wikimedia Commons, then
 * Gemini Vision semantic review. Vision is advisory only — it never writes to
 * the Draft. Only an explicit Admin Accept call attaches media. */
@Injectable()
export class CourseMediaSearchService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly upload: UploadService,
    private readonly imageSearch: ImageSearchProviderChain,
    private readonly vision: AiImageSemanticValidator,
    @Optional() @InjectRedis() private readonly redis?: Redis,
  ) {}

  private admin(user: Admin) {
    if (user.role !== Role.ADMIN) throw new ForbiddenException('Admin only');
  }

  private async course(courseId: number) {
    const course = await this.prisma.course.findUnique({
      where: { id: courseId },
    });
    if (!course) throw new NotFoundException('Course not found');
    return course;
  }

  private async lesson(courseId: number, lessonId: number) {
    const lesson = await this.prisma.courseLesson.findFirst({
      where: { id: lessonId, courseId },
    });
    if (!lesson) throw new NotFoundException('Lesson not found');
    return lesson;
  }

  private assertCourseEditable(course: { status: CourseStatus }) {
    if (course.status === CourseStatus.PUBLISHED)
      throw new ConflictException(
        'Khóa học đã được xuất bản. Hãy chuyển khóa học về bản nháp trước khi thay đổi ảnh.',
      );
  }

  private async editableCourse(courseId: number) {
    const course = await this.course(courseId);
    this.assertCourseEditable(course);
    return course;
  }

  private async editableLesson(courseId: number, lessonId: number) {
    const [course, lesson] = await Promise.all([
      this.course(courseId),
      this.lesson(courseId, lessonId),
    ]);
    this.assertCourseEditable(course);
    if (lesson.status === CourseLessonStatus.PUBLISHED)
      throw new ConflictException(
        'Bài học đã được xuất bản. Hãy chuyển bài học về bản nháp trước khi thay đổi ảnh.',
      );
    return lesson;
  }

  private levelLabel(level?: string | null) {
    return LEVEL_LABEL[level ?? ''] ?? 'beginner';
  }

  /** Deterministic keyword query from Course title/level — no extra Gemini
   * text call. Image search providers match short keyword phrases far better
   * than full sentences, so this stays separate from the richer Vision
   * context string passed alongside it. */
  private deriveCourseCoverBrief(
    course: { title: string; level?: string | null },
    firstLessonTitle?: string,
  ) {
    const topic = keywordize(firstLessonTitle?.trim() || course.title);
    return `${this.levelLabel(course.level)} english learners ${topic}`.slice(
      0,
      160,
    );
  }

  /** Deterministic keyword query from Lesson title — no extra Gemini text call. */
  private deriveLessonMediaBrief(lesson: { title: string }) {
    return `people ${keywordize(lesson.title)}`.slice(0, 160);
  }

  private extensionFor(mimeType: string) {
    return mimeType.split('/')[1]?.replace('jpeg', 'jpg') || 'jpg';
  }

  /** Short pedagogically-relevant image-generation prompt — deliberately NOT
   * the full Course JSON, just title/level distilled into a scene brief. */
  private deriveCourseCoverGenerationPrompt(
    course: { title: string; level?: string | null },
    firstLessonTitle?: string,
  ) {
    const topic = firstLessonTitle?.trim() || course.title;
    return (
      `${this.levelLabel(course.level)} friendly diverse adult learners practicing ${topic}, ` +
      'bright natural classroom or casual learning environment, professional educational photography, ' +
      'landscape composition, no text, no logos'
    ).slice(0, 300);
  }

  private deriveLessonMediaGenerationPrompt(lesson: { title: string }) {
    return (
      `two people ${lesson.title.toLowerCase()}, friendly everyday conversation, ` +
      'natural realistic setting, educational lifestyle photography, landscape, no text, no logos'
    ).slice(0, 300);
  }

  private generationMetadataKey(token: string) {
    return `media-gen:token:${token}`;
  }

  private generationLatestKey(
    mediaType: GeneratedMediaType,
    courseId: number,
    lessonId?: number,
  ) {
    return `media-gen:latest:${mediaType}:${courseId}:${lessonId ?? '-'}`;
  }

  private async readGenerationMetadata(
    token: string,
  ): Promise<GeneratedMediaMetadata | null> {
    if (!this.redis) return null;
    const raw = await this.redis.get(this.generationMetadataKey(token));
    if (!raw) return null;
    try {
      return JSON.parse(raw) as GeneratedMediaMetadata;
    } catch {
      return null;
    }
  }

  private async safeDeleteObject(key: string) {
    try {
      await this.upload.deleteFile(key);
    } catch {
      // best-effort cleanup only — an orphaned temp object is acceptable
      // debt, never worth failing the caller's request over.
    }
  }

  private async safeRedisDel(key: string) {
    if (!this.redis) return;
    try {
      await this.redis.del(key);
    } catch {
      // best-effort — see safeDeleteObject
    }
  }

  /** Deletes the temp R2 object + Redis metadata for a token. Used both for
   * routine post-Accept cleanup and for invalidating a stale/previous
   * candidate when the Admin regenerates for the same target. Never throws. */
  private async invalidateGenerationToken(
    token: string,
    meta?: GeneratedMediaMetadata | null,
  ) {
    const resolved =
      meta === undefined ? await this.readGenerationMetadata(token) : meta;
    if (resolved) await this.safeDeleteObject(resolved.temporaryObjectKey);
    await this.safeRedisDel(this.generationMetadataKey(token));
  }

  /** Calls Cloudflare Workers AI (FLUX.1-schnell) — the only image-generation
   * path used here; Gemini image-generation models are never called. Returns
   * a classified reason instead of throwing, so callers can report the exact
   * cause (not configured vs technically failed) to the Admin. */
  private async callCloudflareGeneration(prompt: string): Promise<
    | {
        ok: true;
        buffer: Buffer;
        mimeType: string;
        width: number;
        height: number;
      }
    | { ok: false; reason: MediaGenerationReason }
  > {
    const accountId = process.env.CLOUDFLARE_ACCOUNT_ID?.trim();
    const token = process.env.CLOUDFLARE_AI_API_TOKEN?.trim();
    if (!accountId || !token)
      return { ok: false, reason: 'AI_IMAGE_GENERATION_NOT_CONFIGURED' };
    const url = `https://api.cloudflare.com/client/v4/accounts/${accountId}/ai/run/${CLOUDFLARE_MODEL}`;
    let response: Response;
    try {
      response = await fetch(url, {
        method: 'POST',
        headers: {
          Authorization: `Bearer ${token}`,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({ prompt }),
        signal: AbortSignal.timeout(30_000),
      });
    } catch {
      return { ok: false, reason: 'AI_IMAGE_GENERATION_FAILED' };
    }
    if (!response.ok)
      return { ok: false, reason: 'AI_IMAGE_GENERATION_FAILED' };
    let body: { result?: { image?: string } };
    try {
      body = (await response.json()) as { result?: { image?: string } };
    } catch {
      return { ok: false, reason: 'AI_IMAGE_GENERATION_FAILED' };
    }
    const base64 = body?.result?.image;
    if (!base64 || typeof base64 !== 'string')
      return { ok: false, reason: 'AI_IMAGE_GENERATION_FAILED' };
    try {
      const buffer = Buffer.from(base64, 'base64');
      const validated = validateImageBuffer(buffer, 'image/jpeg');
      return {
        ok: true,
        buffer: validated.buffer,
        mimeType: validated.mimeType,
        width: validated.width,
        height: validated.height,
      };
    } catch {
      return { ok: false, reason: 'AI_IMAGE_GENERATION_FAILED' };
    }
  }

  /** Flow: Cloudflare AI → raster bytes → technical validation → Vision →
   * temp R2 object → Redis token metadata → candidate returned to Admin.
   * Nothing is kept in process memory — a candidate generated on one backend
   * instance can be Accepted on any other. */
  private async runGeneration(
    prompt: string,
    context: string,
    target: {
      mediaType: GeneratedMediaType;
      courseId: number;
      lessonId?: number;
    },
  ) {
    const result = await this.callCloudflareGeneration(prompt);
    if (!result.ok)
      return { candidate: null, vision: null, reason: result.reason };
    const vision = await this.vision.validate({
      taskType: 'COURSE_LESSON_IMAGE',
      imageBuffer: result.buffer,
      mimeType: result.mimeType,
      imageBrief: prompt,
      context,
    });
    if (vision.status === 'FAIL')
      return {
        candidate: null,
        vision,
        reason: 'VISION_REJECTED_ALL' as const,
      };

    const token = randomUUID();
    const temporaryObjectKey = `tmp/course-media/${token}/generated.${this.extensionFor(result.mimeType)}`;
    try {
      await this.upload.putObjectAtKey(
        temporaryObjectKey,
        result.buffer,
        result.mimeType,
      );
    } catch {
      return {
        candidate: null,
        vision,
        reason: 'AI_IMAGE_GENERATION_STORAGE_FAILED' as const,
      };
    }

    const metadata: GeneratedMediaMetadata = {
      token,
      temporaryObjectKey,
      mediaType: target.mediaType,
      courseId: target.courseId,
      lessonId: target.lessonId,
      mimeType: result.mimeType,
      width: result.width,
      height: result.height,
      generatedAt: Date.now(),
      provider: 'CLOUDFLARE_WORKERS_AI',
      model: CLOUDFLARE_MODEL,
      semanticStatus: vision.status,
    };
    try {
      if (!this.redis) throw new Error('redis not configured');
      const latestKey = this.generationLatestKey(
        target.mediaType,
        target.courseId,
        target.lessonId,
      );
      // "Sinh ảnh khác": clean up the previous outstanding candidate for the
      // same target instead of accumulating temp objects per session.
      const previousToken = await this.redis.get(latestKey);
      if (previousToken && previousToken !== token)
        await this.invalidateGenerationToken(previousToken);
      await this.redis.set(
        this.generationMetadataKey(token),
        JSON.stringify(metadata),
        'EX',
        GENERATION_TOKEN_TTL_SECONDS,
      );
      await this.redis.set(
        latestKey,
        token,
        'EX',
        GENERATION_TOKEN_TTL_SECONDS,
      );
    } catch {
      await this.safeDeleteObject(temporaryObjectKey);
      return {
        candidate: null,
        vision,
        reason: 'TEMP_MEDIA_STORAGE_UNAVAILABLE' as const,
      };
    }

    const reason: MediaGenerationReason =
      vision.status === 'UNAVAILABLE' ? 'VISION_UNAVAILABLE' : 'SUCCESS';
    return {
      candidate: {
        token,
        previewUrl: `data:${result.mimeType};base64,${result.buffer.toString('base64')}`,
      },
      vision,
      reason,
    };
  }

  private async runSearch(brief: string, context: string) {
    const { candidates, attempted } =
      await this.imageSearch.searchWithDiagnostics(brief, {
        limit: MAX_MEDIA_CANDIDATES_TO_VISION,
      });
    if (!candidates.length) {
      const reason: MediaSearchReason = attempted.some(
        (a) => a.outcome === 'OK_EMPTY',
      )
        ? 'SEARCH_NO_RESULT'
        : 'SEARCH_PROVIDER_UNAVAILABLE';
      return { candidate: null, vision: null, brief, reason };
    }

    let anyDownloaded = false;
    // UNAVAILABLE is advisory, not a rejection (see AiImageSemanticValidator):
    // keep the first such candidate as a fallback for Admin's own judgment,
    // but keep looking for a candidate Vision can actually confirm first.
    let firstUnavailable: {
      candidate: ImageSearchCandidate;
      vision: Awaited<ReturnType<AiImageSemanticValidator['validate']>>;
    } | null = null;
    for (const candidate of candidates.slice(
      0,
      MAX_MEDIA_CANDIDATES_TO_VISION,
    )) {
      let downloaded;
      try {
        downloaded = await this.imageSearch.download(candidate);
      } catch {
        continue; // technically invalid/unreachable candidate — try the next one
      }
      anyDownloaded = true;
      const vision = await this.vision.validate({
        taskType: 'COURSE_LESSON_IMAGE',
        imageBuffer: downloaded.buffer,
        mimeType: downloaded.mimeType,
        imageBrief: brief,
        context,
      });
      if (vision.status === 'FAIL') continue;
      if (vision.status === 'UNAVAILABLE') {
        firstUnavailable ??= { candidate, vision };
        continue;
      }
      return { candidate, vision, brief, reason: 'SUCCESS' as const };
    }
    if (firstUnavailable)
      return {
        candidate: firstUnavailable.candidate,
        vision: firstUnavailable.vision,
        brief,
        reason: 'VISION_UNAVAILABLE' as const,
      };
    const reason: MediaSearchReason = !anyDownloaded
      ? 'SEARCH_PROVIDER_UNAVAILABLE'
      : 'VISION_REJECTED_ALL';
    return { candidate: null, vision: null, brief, reason };
  }

  async searchCourseCover(
    courseId: number,
    dto: SearchCourseMediaDto,
    user: Admin,
  ) {
    this.admin(user);
    const course = await this.editableCourse(courseId);
    const firstLesson = await this.prisma.courseLesson.findFirst({
      where: { courseId },
      orderBy: { order: 'asc' },
      select: { title: true },
    });
    const brief =
      dto.brief?.trim() ||
      this.deriveCourseCoverBrief(course, firstLesson?.title);
    return this.runSearch(brief, `Course cover for: ${course.title}`);
  }

  async searchLessonMedia(
    courseId: number,
    lessonId: number,
    dto: SearchCourseMediaDto,
    user: Admin,
  ) {
    this.admin(user);
    const lesson = await this.editableLesson(courseId, lessonId);
    const brief = dto.brief?.trim() || this.deriveLessonMediaBrief(lesson);
    return this.runSearch(
      brief,
      `Lesson representative image for: ${lesson.title}`,
    );
  }

  /** Re-downloads and re-validates the candidate's raster bytes (never trusts
   * the client-supplied record for anything beyond which provider/URL to
   * fetch), then stores it in R2. Vision is not re-run — it already ran
   * during search; Accept is the Admin's explicit, final decision. */
  async acceptCourseCover(
    courseId: number,
    dto: AcceptCourseMediaDto,
    user: Admin,
  ) {
    this.admin(user);
    await this.editableCourse(courseId);
    const downloaded = await this.imageSearch.download(dto.candidate);
    const key = `courses/${courseId}/cover-${Date.now()}.${this.extensionFor(downloaded.mimeType)}`;
    const uploaded = await this.upload.putObjectAtKey(
      key,
      downloaded.buffer,
      downloaded.mimeType,
    );
    await this.prisma.course.update({
      where: { id: courseId },
      data: { thumbnail: uploaded.url },
    });
    return { thumbnail: uploaded.url };
  }

  async acceptLessonMedia(
    courseId: number,
    lessonId: number,
    dto: AcceptCourseMediaDto,
    user: Admin,
  ) {
    this.admin(user);
    const lesson = await this.editableLesson(courseId, lessonId);
    const downloaded = await this.imageSearch.download(dto.candidate);
    const key = `courses/${courseId}/lessons/${lessonId}/media-${Date.now()}.${this.extensionFor(downloaded.mimeType)}`;
    const uploaded = await this.upload.putObjectAtKey(
      key,
      downloaded.buffer,
      downloaded.mimeType,
    );
    const media = await this.prisma.courseLessonMedia.create({
      data: {
        lessonId,
        type: 'image',
        url: uploaded.url,
        altText: lesson.title,
        provenance: `auto-retrieved:${dto.candidate.provider.toLowerCase()}`,
      },
    });
    return { media };
  }

  /** "Sinh ảnh bằng AI" — a separate, explicit authoring action from "Tìm ảnh
   * phù hợp". Never invoked automatically when search fails. Generates
   * exactly ONE candidate per call (Admin may explicitly ask again). */
  async generateCourseCoverImage(courseId: number, user: Admin) {
    this.admin(user);
    const course = await this.editableCourse(courseId);
    const firstLesson = await this.prisma.courseLesson.findFirst({
      where: { courseId },
      orderBy: { order: 'asc' },
      select: { title: true },
    });
    const prompt = this.deriveCourseCoverGenerationPrompt(
      course,
      firstLesson?.title,
    );
    return this.runGeneration(prompt, `Course cover for: ${course.title}`, {
      mediaType: 'COURSE_COVER',
      courseId,
    });
  }

  async generateLessonMediaImage(
    courseId: number,
    lessonId: number,
    user: Admin,
  ) {
    this.admin(user);
    const lesson = await this.editableLesson(courseId, lessonId);
    const prompt = this.deriveLessonMediaGenerationPrompt(lesson);
    return this.runGeneration(
      prompt,
      `Lesson representative image for: ${lesson.title}`,
      { mediaType: 'LESSON_IMAGE', courseId, lessonId },
    );
  }

  /** Resolves + validates target ownership WITHOUT consuming the token — a
   * mismatch must never mutate the token/temp-object state, so a retry with
   * the correct target still works. */
  private async resolveGenerationMetadata(
    token: string,
    mediaType: GeneratedMediaType,
    courseId: number,
    lessonId?: number,
  ): Promise<GeneratedMediaMetadata> {
    const meta = await this.readGenerationMetadata(token);
    if (!meta)
      throw new NotFoundException(
        'Ảnh AI đã hết hạn hoặc không còn tồn tại. Hãy sinh ảnh mới.',
      );
    const belongsToTarget =
      meta.mediaType === mediaType &&
      meta.courseId === courseId &&
      (mediaType !== 'LESSON_IMAGE' || meta.lessonId === lessonId);
    if (!belongsToTarget)
      throw new ForbiddenException('Ảnh đề xuất không thuộc về mục tiêu này.');
    return meta;
  }

  async acceptGeneratedCourseCover(
    courseId: number,
    dto: AcceptGeneratedMediaDto,
    user: Admin,
  ) {
    this.admin(user);
    await this.editableCourse(courseId);
    const meta = await this.resolveGenerationMetadata(
      dto.token,
      'COURSE_COVER',
      courseId,
    );
    const bytes = await this.upload.downloadFileBuffer(meta.temporaryObjectKey);
    const validated = validateImageBuffer(bytes, meta.mimeType);
    const key = `courses/${courseId}/cover-${Date.now()}.${this.extensionFor(validated.mimeType)}`;
    const uploaded = await this.upload.putObjectAtKey(
      key,
      validated.buffer,
      validated.mimeType,
    );
    try {
      await this.prisma.course.update({
        where: { id: courseId },
        data: { thumbnail: uploaded.url },
      });
    } catch (err) {
      await this.safeDeleteObject(uploaded.key);
      throw err;
    }
    await this.invalidateGenerationToken(dto.token, meta);
    await this.safeRedisDel(this.generationLatestKey('COURSE_COVER', courseId));
    return { thumbnail: uploaded.url };
  }

  async acceptGeneratedLessonMedia(
    courseId: number,
    lessonId: number,
    dto: AcceptGeneratedMediaDto,
    user: Admin,
  ) {
    this.admin(user);
    const lesson = await this.editableLesson(courseId, lessonId);
    const meta = await this.resolveGenerationMetadata(
      dto.token,
      'LESSON_IMAGE',
      courseId,
      lessonId,
    );
    const bytes = await this.upload.downloadFileBuffer(meta.temporaryObjectKey);
    const validated = validateImageBuffer(bytes, meta.mimeType);
    const key = `courses/${courseId}/lessons/${lessonId}/media-${Date.now()}.${this.extensionFor(validated.mimeType)}`;
    const uploaded = await this.upload.putObjectAtKey(
      key,
      validated.buffer,
      validated.mimeType,
    );
    let media;
    try {
      media = await this.prisma.courseLessonMedia.create({
        data: {
          lessonId,
          type: 'image',
          url: uploaded.url,
          altText: lesson.title,
          provenance: `generated:cloudflare-workers-ai:flux-1-schnell`,
        },
      });
    } catch (err) {
      await this.safeDeleteObject(uploaded.key);
      throw err;
    }
    await this.invalidateGenerationToken(dto.token, meta);
    await this.safeRedisDel(
      this.generationLatestKey('LESSON_IMAGE', courseId, lessonId),
    );
    return { media };
  }
}
